#!/usr/bin/env node
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createHash} from 'node:crypto';
import {Script} from 'node:vm';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const v6=fs.readFileSync(new URL('../www/index.html',import.meta.url));
assert.equal(createHash('sha256').update(v6).digest('hex'),'2988addb825d5021c343e2969157ac602fbbf5db795821390c547705e9189cb7','V6 release immutable');
assert.ok(read('www/story-first/index.html').includes('id="origin16"'),'Original Story First still exists');
assert.ok(read('www/v7/index.html').includes('ORIGIN / V7 Alpha'),'V7 preserved');
assert.ok(read('www/life/app.js').includes('origin_v8_life_scene_v1'),'V8 reader still exists');
const v9js=read('www/app/app.js'),v10js=read('www/v10/app.js');
const opening=code=>code.slice(code.indexOf('function beginAnimation(){'),code.indexOf('function journeyTarget(type){'));
assert.ok(opening(v9js).length>1000);
assert.equal(opening(v10js),opening(v9js),'Welcome animation must be kept exactly');
const v9html=read('www/app/index.html'),v10html=read('www/v10/index.html');
const welcome=code=>code.slice(code.indexOf('<div id="welcome"'),code.indexOf('<div id="app"'));
assert.equal(welcome(v10html),welcome(v9html),'Welcome artwork and wording must remain identical');
assert.equal((v10html.match(/COMING SOON/g)||[]).length,4,'Four distinct future creators');
for(const name of ['Akira','Ghatak','Varda','Kubrick'])assert.ok(v10html.includes(name));
assert.ok(v10js.includes("'/v10/journey/#scene-'"));
const story=read('www/v10/journey/story.js'),h=read('www/v10/journey/index.html'),css=read('www/v10/journey/styles.css');
for(const id of ['archiveImage','storyTitle','storyLead','yearPlace','contextDialog','mapDialog','next','prev','completion','sourceLinks'])assert.ok(h.includes('id="'+id+'"'),'Missing journey element '+id);
assert.ok(story.includes('origin_v10_act1_scene_v1'));
assert.ok(story.includes('https://satyajitray.org/growing-up/'));
assert.ok(story.includes('1939')&&story.includes('1921')&&story.includes('1923'));
assert.ok(css.includes('prefers-reduced-motion')&&css.includes('@media(max-width:650px)'));
new Script(v10js,{filename:'www/v10/app.js'});new Script(story,{filename:'www/v10/journey/story.js'});
console.log('V10 static QA: originals unchanged, welcome byte-for-byte, four future creators, history-grounded Act I and JS syntax all PASSED.');
