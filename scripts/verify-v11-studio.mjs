#!/usr/bin/env node
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {Script,createContext} from 'node:vm';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const context=createContext({window:{},URL,console});
new Script(read('www/v11/studio/schema.js'),{filename:'schema.js'}).runInContext(context,{timeout:2000});
const s=context.window.ORIGIN_STUDIO_SCHEMA;
const normalize=v=>JSON.parse(JSON.stringify(v));
assert.ok(s,'Studio schema must register');
const empty=normalize(s.blank());
assert.equal(s.validate(empty).ok,false,'Empty draft cannot be previewed');
const example=normalize(s.demo());
const result=s.validate(example);
assert.equal(result.ok,true,result.errors.join('\n'));
assert.equal(result.warnings.length,1,'Sample has outstanding image rights review');
const compiled=normalize(s.compile(example));
assert.equal(compiled.profile.id,'studio-local','Drafts cannot overwrite canonical creators');
assert.equal(compiled.profile.preview,true);
assert.equal(compiled.acts.length,1);
assert.equal(compiled.acts[0].scenes.length,1);
assert.equal(compiled.acts[0].scenes[0].sources[0],0,'Source IDs convert to renderer source indexes');
assert.equal(compiled.acts[0].scenes[0].asset,undefined,'External media is never loaded in draft preview');
assert.match(compiled.acts[0].scenes[0].visual,/no licensed media displayed/);
assert.equal(compiled.acts[0].scenes[0].bg.startsWith('radial-gradient('),true);
assert.ok(s.TEMPLATES.length>=10);
function copy(){return JSON.parse(JSON.stringify(example));}
const unsafeUrl=copy();unsafeUrl.acts[0].archive[0].url='javascript:alert(1)';
assert.equal(s.validate(unsafeUrl).ok,false,'Untrusted citation URLs are not previewable');
const authUrl=copy();authUrl.acts[0].archive[0].url='https://user:pass@example.org/';
assert.equal(s.validate(authUrl).ok,false,'Credentialed source URLs disallowed');
const markup=copy();markup.acts[0].scenes[0].title='<img src=x onerror=alert(1)>';
assert.equal(s.validate(markup).ok,false,'HTML scene titles are not accepted in Studio');
const wrongCitation=copy();wrongCitation.acts[0].scenes[0].sources=['invented-source'];
assert.equal(s.validate(wrongCitation).ok,false,'Every citation resolves to a declared research source');
const noCitations=copy();noCitations.acts[0].scenes[0].sources=[];
assert.equal(s.validate(noCitations).ok,false,'Scenes without sources cannot be previewed');
const invalidRights=copy();invalidRights.acts[0].scenes[0].rights='cleared';
assert.equal(s.validate(invalidRights).ok,false,'Cleared rights need evidence');
invalidRights.acts[0].scenes[0].rightsNote='Written permission from verified rights holder';
assert.equal(s.validate(invalidRights).ok,true);
const unsafeStyle=copy();unsafeStyle.profile.identity.accent='red; background:url(evil)';
assert.equal(s.validate(unsafeStyle).ok,false,'No arbitrary CSS values');
const template=copy();template.acts[0].scenes[0].visualTemplate='custom-script';
assert.equal(s.validate(template).ok,false,'Only supported visual scene presets');
const oversized=copy();oversized.acts[0].scenes[0].more='x'.repeat(310000);
assert.equal(s.validate(oversized).ok,false,'Reject excessively large imports');
const second=copy();
second.acts.push(normalize(s.act()));
second.acts[1].name='A second chapter';second.acts[1].period='1930';second.acts[1].archive=[{id:'second-source',label:'Source two',url:'https://example.com/'}];
const sc=second.acts[1].scenes[0];Object.assign(sc,{year:'1930',place:'SECOND LOCATION',title:'A second story',lead:'This is a complete hypothetical scene example',more:'This is a longer explanatory sentence for a demonstration',history:'Source two supports the dated scene details',meaning:'The next moment matters',sources:['second-source']});
assert.equal(s.validate(second).ok,true,s.validate(second).errors.join('; '));
assert.deepEqual(normalize(s.compile(second).acts.map(x=>x.index)),[1,2],'Chapters compile sequentially without special code');
const html=read('www/v11/studio/index.html'),editor=read('www/v11/studio/editor.js');
for(const id of ['studioHeading','newDraft','saveDraft','loadSample','exportDraft','importDraft','checkDraft','previewDraft','status','profileTab','actList','addAct','editorFields','qaStatus','qaResults']){
 assert.ok(html.includes('id="'+id+'"'),'Studio element missing '+id);
}
for(const [,id] of editor.matchAll(/\$\('([A-Za-z0-9_-]+)'\)/g))assert.ok(html.includes('id="'+id+'"'),'Editor references missing '+id);
for(const filename of ['editor.js','preview.js'])new Script(read('www/v11/studio/'+filename),{filename});
assert.ok(html.includes('href="/v11/?person=studio-local&amp;draft=1#act=1&amp;scene=0"'),'Preview opens real V11 player');
assert.ok(html.includes('NOT PUBLISHED')&&html.includes('public website'),'Risk notices must be explicit');
assert.ok(!html.includes('Publish</'),'No public publish feature');
const viewer=read('www/v11/index.html');
assert.ok(viewer.includes('src="./studio/schema.js"')&&viewer.includes('src="./studio/preview.js"'));
assert.ok(viewer.indexOf('./studio/preview.js')<viewer.indexOf('./player.js'),'Local preview registers before player');
assert.ok(viewer.includes('href="/v11/studio/"'),'Studio must be discoverable');
const preview=read('www/v11/studio/preview.js');
assert.ok(preview.includes("q.get('draft')!=='1'"),'Preview bridge must be opt in');
assert.ok(preview.includes("q.get('person')!=='studio-local'"),'Cannot overwrite a public creator');
assert.ok(!preview.includes('fetch(')&&!editor.includes('fetch('),'No server upload/read of drafts');
const css=read('www/v11/studio/studio.css');
assert.ok(css.includes('max-width:720px')&&css.includes('min-width:320px'),'Mobile authoring layout required');
console.log('ORIGIN V11.3 Studio static QA PASS: local drafts, required citations, image rights, validation, safe preview compilation, import/export UI and no publish path.');
